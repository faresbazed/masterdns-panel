def render_server_config(settings, users):
    with open(TEMPLATE_PATH, "r", encoding="utf-8") as fh:
        text = fh.read()
    domains = [user_domain(settings, u) for u in users
               if u.get("enabled", True) and not user_expired(u)]
    if not domains:  # keep the service able to start before the first user
        existing = {user_domain(settings, u).rstrip(".").lower() for u in users}
        placeholder, n = setup_domain(settings), 2
        while placeholder.lower() in existing:
            placeholder = setup_domain(settings, f"setup-{n}")
            n += 1
        domains = [placeholder]
    domain_list = "[" + ", ".join(f'"{d}"' for d in domains) + "]"
    text = re.sub(r'^DOMAIN\s*=.*$', f"DOMAIN = {domain_list}",
                  text, count=1, flags=re.M)
    text = re.sub(r'^DATA_ENCRYPTION_METHOD\s*=.*$',
                  f"DATA_ENCRYPTION_METHOD = {int(settings['encryption_method'])}",
                  text, count=1, flags=re.M)
    text = re.sub(r'^ENCRYPTION_KEY_FILE\s*=.*$',
                  f'ENCRYPTION_KEY_FILE = "{SERVER_KEY_FILE}"',
                  text, count=1, flags=re.M)
    header = ("# Generated by MasterDNS Panel — do not edit by hand.\n"
              f"# Tunnel domains: {', '.join(domains)}\n\n")
    return header + text


def sync_server(restart=True):
    with SYNC_LOCK:
        return _sync_server(restart)


def _sync_server(restart):
    global APPLIED_CONFIG
    settings, users = load_settings(), load_users()
    try:
        os.makedirs(SERVER_DIR, exist_ok=True)
        # The key file must exist with the exact length the method requires,
        # or the server regenerates it and every issued link breaks.
        current = ""
        if os.path.exists(SERVER_KEY_FILE):
            with open(SERVER_KEY_FILE, "r", encoding="utf-8") as fh:
                current = fh.read().strip()
        if current != settings["key"]:
            with open(SERVER_KEY_FILE, "w", encoding="utf-8") as fh:
                fh.write(settings["key"])
            os.chmod(SERVER_KEY_FILE, 0o600)
        config = render_server_config(settings, users)
        with open(SERVER_CONFIG, "w", encoding="utf-8") as fh:
            fh.write(config)
        if restart and RESTART_CMD:
            proc = subprocess.run(RESTART_CMD, shell=True, capture_output=True,
                                  text=True, timeout=30)
            if proc.returncode != 0:
                raise RuntimeError((proc.stderr or proc.stdout or "restart failed").strip())
        if restart:
            APPLIED_CONFIG = config
        LAST_SYNC.update(ok=True, message="server config synced"
                         + (" and service restarted" if restart and RESTART_CMD else ""))
    except Exception as exc:  # panel must stay up even if the service is not installed yet
        LAST_SYNC.update(ok=False, message=f"sync failed: {exc}")
    return LAST_SYNC["ok"]


def sync_if_stale():
    with SYNC_LOCK:
        return _sync_if_stale()


def _sync_if_stale():
    expected = render_server_config(load_settings(), load_users())
    try:
        with open(SERVER_CONFIG, "r", encoding="utf-8") as fh:
            current = fh.read()
    except FileNotFoundError:
        current = None
    if current == expected == APPLIED_CONFIG and LAST_SYNC["ok"] is not False:
        return False
    return sync_server(restart=True)


def watch_expiry():
    while True:
        time.sleep(EXPIRY_CHECK_INTERVAL)
        try:
            sync_if_stale()
        except Exception as exc:
            LAST_SYNC.update(ok=False, message=f"expiry check failed: {exc}")


def user_expired(user):
    expiry = (user.get("expiry") or "").strip()
    return bool(expiry and expiry < time.strftime("%Y-%m-%d"))


def server_status():
    try:
        proc = subprocess.run("systemctl is-active masterdnsvpn.service",
                              shell=True, capture_output=True, text=True, timeout=5)
        return proc.stdout.strip() or "unknown"
    except Exception:
        return "unknown (no systemd)"


def slugify(name):
    slug = re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")
    slug = re.sub(r"-{2,}", "-", slug)[:24].strip("-")
    return slug or "user"


def chosen_presets(resolvers):
    """Presets whose every IP is in `resolvers` (ticked in the edit form)."""
    return [name for name, ips in RESOLVER_PRESETS.items() if set(ips) <= set(resolvers)]


def custom_resolvers(resolvers):
    """Resolvers not covered by a chosen preset (the edit form's free-text field)."""
    covered = {ip for name in chosen_presets(resolvers) for ip in RESOLVER_PRESETS[name]}
    return [r for r in resolvers if r not in covered]


def parse_resolvers(form):
    chosen = []
    for preset in form.getlist("presets"):
        chosen += RESOLVER_PRESETS.get(preset, [])
    custom = form.getvalue("custom_resolvers", "") or ""
    for token in re.split(r"[,\s]+", custom):
        token = token.strip()
        if token:
            chosen.append(token)
    seen, out = set(), []
    for item in chosen:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out or list(DEFAULT_RESOLVERS)


