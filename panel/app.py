def user_domain(settings, user):
    return user.get("custom_domain") or f"{user['slug']}.{settings['base_domain']}"


def setup_domain(settings, slug="setup"):
    return f"{slug}.{settings['base_domain'].rstrip('.')}"


def taken_domains(settings, users):
    """Domains reserved for setup, the nameserver, or existing users."""
    domains = {setup_domain(settings), settings["ns_host"],
               *(user_domain(settings, u) for u in users)}
    return {d.rstrip(".") for d in domains}


def simple_link(settings, user):
    """Canonical masterdns:// link (Hiddify + V2Box)."""
    q = urllib.parse.urlencode({
        "key": settings["key"],
        "resolvers": ",".join(user["resolvers"]),
        "encryption": ENC_NAMES[int(settings["encryption_method"])],
    })
    name = urllib.parse.quote(user["name"])
    return f"masterdns://{user_domain(settings, user)}?{q}#{name}"


def json_link(settings, user):
    """Long Hiddify form: base64 of the MasterDnsVPN client JSON config."""
    cfg = {
        "DOMAINS": [user_domain(settings, user)],
        "ENCRYPTION_KEY": settings["key"],
        "DATA_ENCRYPTION_METHOD": int(settings["encryption_method"]),
        "PROTOCOL_TYPE": "SOCKS5",
        "RESOLVERS": user["resolvers"],
    }
    raw = json.dumps(cfg, separators=(",", ":")).encode()
    body = base64.urlsafe_b64encode(raw).decode().rstrip("=")
    return f"masterdns://{body}#{urllib.parse.quote(user['name'])}"


def dnst_link(settings, user):
    """dnst:// link (dnst URL spec; also read by Hiddify)."""
    q = urllib.parse.urlencode({
        "mkey": settings["key"],
        "encryption": int(settings["encryption_method"]),
        "resolvers": ",".join(user["resolvers"]),
    })
    name = urllib.parse.quote(user["name"])
    return f"dnst://{user_domain(settings, user)}/masterdns/socks?{q}#{name}"


def client_zip(settings, user):
    """client_config.toml + client_resolvers.txt for the original client."""
    domain = user_domain(settings, user)
    toml = f"""# MasterDnsVPN client config for {user['name']} — generated by MasterDNS Panel
DOMAINS = ["{domain}"]
DATA_ENCRYPTION_METHOD = {int(settings['encryption_method'])}
ENCRYPTION_KEY = "{settings['key']}"
PROTOCOL_TYPE = "SOCKS5"
LISTEN_IP = "127.0.0.1"
LISTEN_PORT = 18000
LOG_LEVEL = "INFO"
"""
    resolvers = "\n".join(user["resolvers"]) + "\n"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("client_config.toml", toml)
        zf.writestr("client_resolvers.txt", resolvers)
    return buf.getvalue()


