def cmd_init(args):
    os.makedirs(PANEL_HOME, exist_ok=True)
    os.makedirs(SERVER_DIR, exist_ok=True)
    method = int(args.encryption_method)
    settings = {
        "base_domain": args.base_domain.strip().lower(),
        "ns_host": args.ns_host.strip().lower(),
        "server_ip": args.server_ip or "",
        "encryption_method": method,
        "key": make_key(method),
        "admin_hash": hash_password(args.admin_password),
        "installed_at": time.strftime("%Y-%m-%d %H:%M"),
    }
    save_settings(settings)
    if not os.path.exists(USERS_FILE):
        save_users([])
    sync_server(restart=False)
    print(f"Panel initialised. Base domain: {settings['base_domain']}  "
          f"Nameserver: {settings['ns_host']}  Encryption: {ENC_NAMES[method]}")
    print(f"Server config written to {SERVER_CONFIG}")


def cmd_serve(args):
    global APPLIED_CONFIG
    if not os.path.exists(SETTINGS_FILE):
        sys.exit("Panel is not initialised — run `app.py init ...` first (install.sh does this).")
    try:
        with open(SERVER_CONFIG, "r", encoding="utf-8") as fh:
            APPLIED_CONFIG = fh.read()
    except FileNotFoundError:
        APPLIED_CONFIG = None
    sync_server(restart=False)
    server = ThreadingHTTPServer((args.host, args.port), Handler)
    threading.Thread(target=watch_expiry, daemon=True).start()
    print(f"MasterDNS Panel listening on http://{args.host}:{args.port}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


def main():
    parser = argparse.ArgumentParser(description="MasterDNS Panel for MasterDnsVPN")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_init = sub.add_parser("init")
    p_init.add_argument("--base-domain", required=True)
    p_init.add_argument("--ns-host", required=True)
    p_init.add_argument("--admin-password", required=True)
    p_init.add_argument("--server-ip", default="")
    p_init.add_argument("--encryption-method", default="5")
    p_serve = sub.add_parser("serve")
    p_serve.add_argument("--host", default="0.0.0.0")
    p_serve.add_argument("--port", type=int, default=8080)
    args = parser.parse_args()
    (cmd_init if args.cmd == "init" else cmd_serve)(args)


if __name__ == "__main__":
    main()
