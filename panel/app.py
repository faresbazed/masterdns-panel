#!/usr/bin/env python3
"""
MasterDNS Panel — a tiny, dependency-free web panel for MasterDnsVPN.

What it does
------------
* Manages users for one MasterDnsVPN server running on the same VPS.
* Every user gets their *own tunnel subdomain*  <slug>.<base-domain>.
  The upstream MasterDnsVPN server accepts a list of tunnel domains in a
  single instance (server config key `DOMAIN = [...]`), so the panel simply
  rewrites that list whenever a user is created / enabled / disabled /
  deleted and restarts the service.  Removing a user's domain from the
  server is what revokes their access — their link stops working even
  though all users share the server's single encryption key + method
  (that is how upstream MasterDnsVPN works: one key file per server).
* Generates copy-paste client links per user, in every format the common
  clients understand:
    - masterdns://<domain>?key=..&resolvers=..&encryption=..#name
      (the canonical form; read by Hiddify via ray2sing and by V2Box)
    - masterdns://<base64 JSON client config>#name     (Hiddify long form)
    - dnst://<domain>/masterdns/socks?mkey=..&encryption=..#name
    - a per-user subscription URL (base64 list) for subscription import
    - a downloadable .zip with client_config.toml + client_resolvers.txt
      for the original desktop / Termux MasterDnsVPN client
* The resolver list is chosen per user (presets or any custom DNS IPs,
  e.g. your ISP's resolver), and is baked into every link the panel makes.

Only Python's standard library is used.  Run:
    python3 app.py init   --base-domain example.com --ns-host ns.example.com \
                          --admin-password 'change-me'
    python3 app.py serve  --port 8080

Environment:
    MDV_HOME         panel data dir   (default /opt/masterdns-panel)
    MDV_SERVER_DIR   MasterDnsVPN server dir (default /opt/masterdns)
    MDV_RESTART_CMD  command run after the server config changes
                     (default: systemctl restart masterdnsvpn.service)
"""

