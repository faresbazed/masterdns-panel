# Upstream DATA_ENCRYPTION_METHOD ids -> names used inside masterdns:// links
# (hiddify-sing-box option/masterdns.go: none, xor, chacha20, aes-128-gcm,
#  aes-192-gcm, aes-256-gcm, or the number 0..5).
ENC_NAMES = {0: "none", 1: "xor", 2: "chacha20",
             3: "aes-128-gcm", 4: "aes-192-gcm", 5: "aes-256-gcm"}
# Required encrypt_key.txt length per method (upstream
# internal/security/encryption_key.go: AES-128 -> 16, AES-192 -> 24,
# everything else -> 32).  A key file with the wrong length is silently
# regenerated by the server on boot, which would break every client link,
# so the panel is strict about this.
KEY_LENGTHS = {0: 32, 1: 32, 2: 32, 3: 16, 4: 24, 5: 32}

