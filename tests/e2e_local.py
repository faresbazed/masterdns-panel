#!/usr/bin/env python3
"""End-to-end test with the REAL upstream MasterDnsVPN server + client
binaries, using only artifacts generated by the panel itself:

  panel --(server_config.toml + encrypt_key.txt)--> real server (UDP :15353)
  panel --(client.zip: client_config.toml + client_resolvers.txt)--> real client
  curl --socks5-hostname 127.0.0.1:18000 --> local HTTP target through the tunnel

The client is pointed at 127.0.0.1:15353 as its "resolver", i.e. the server
plays the resolver role directly — the standard way to smoke-test a DNS
tunnel on one machine. Needs the upstream release binaries; set
MDV_SERVER_BIN / MDV_CLIENT_BIN or let the script download them.

Run this on a normal machine or the VPS itself. Some sandboxes (including
the one this panel was developed in) block replies from UDP servers at the
syscall level (`sendto: operation not permitted` on unconnected sockets),
which makes any DNS tunnel untestable there no matter how correct the
configs are — there, the server log showing received+processed probes is
the furthest verification possible.
"""
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVER_PORT = 15353
SOCKS_PORT = 18000
TARGET_PORT = 18081
MARKER = "masterdns-panel-e2e-ok"


def fetch_binaries(tmp):
    server_bin = os.environ.get("MDV_SERVER_BIN")
    client_bin = os.environ.get("MDV_CLIENT_BIN")
    if server_bin and client_bin:
        return server_bin, client_bin
    base = "https://github.com/masterking32/MasterDnsVPN/releases/latest/download"
    out = {}
    for kind in ("Server", "Client"):
        zip_path = os.path.join(tmp, f"{kind}.zip")
        urllib.request.urlretrieve(f"{base}/MasterDnsVPN_{kind}_Linux_AMD64.zip", zip_path)
        dest = os.path.join(tmp, kind.lower())
        with zipfile.ZipFile(zip_path) as zf:
            zf.extractall(dest)
        for name in os.listdir(dest):
            if name.startswith(f"MasterDnsVPN_{kind}_"):
                out[kind] = os.path.join(dest, name)
                os.chmod(out[kind], 0o755)
    return out["Server"], out["Client"]


def main():
    tmp = tempfile.mkdtemp(prefix="mdv-e2e-")
    panel_home = os.path.join(tmp, "panel_home")
    server_dir = os.path.join(tmp, "server")
    client_dir = os.path.join(tmp, "client")
    target_dir = os.path.join(tmp, "target")
    for d in (panel_home, server_dir, client_dir, target_dir):
        os.makedirs(d)
    os.environ["MDV_HOME"] = panel_home
    os.environ["MDV_SERVER_DIR"] = server_dir
    os.environ["MDV_RESTART_CMD"] = ""

    sys.path.insert(0, os.path.join(ROOT, "panel"))
    import app as panel

    # --- build everything through the panel's own code -------------------
    settings = {
        "base_domain": "example.com", "ns_host": "ns.example.com",
        "server_ip": "203.0.113.10", "encryption_method": 5,
        "key": panel.make_key(5), "admin_hash": panel.hash_password("x"),
    }
    panel.save_settings(settings)
    user = {"id": "e2e1", "name": "E2E", "slug": "e2e", "custom_domain": None,
            "resolvers": [f"127.0.0.1:{SERVER_PORT}"], "enabled": True,
            "expiry": "", "note": "", "token": "e2e-token", "created_at": ""}
    panel.save_users([user])
    assert panel.sync_server(restart=False), "panel sync failed"

    # sandbox-friendly port (a VPS would keep the generated 53)
    cfg_path = os.path.join(server_dir, "server_config.toml")
    cfg = open(cfg_path).read()
    cfg = re.sub(r"^UDP_PORT\s*=.*$", f"UDP_PORT = {SERVER_PORT}", cfg, flags=re.M)
    cfg = re.sub(r"^UDP_HOST\s*=.*$", 'UDP_HOST = "127.0.0.1"', cfg, flags=re.M)
    assert f"UDP_PORT = {SERVER_PORT}" in cfg and '"e2e.example.com"' in cfg
    open(cfg_path, "w").write(cfg)

    with zipfile.ZipFile(io.BytesIO(panel.client_zip(settings, user))) as zf:
        zf.extractall(client_dir)
    assert open(os.path.join(client_dir, "client_resolvers.txt")).read().strip() == f"127.0.0.1:{SERVER_PORT}"

    server_bin, client_bin = fetch_binaries(tmp)
    shutil.copy(server_bin, os.path.join(server_dir, "masterdns-server"))
    shutil.copy(client_bin, os.path.join(client_dir, "masterdns-client"))
    os.chmod(os.path.join(server_dir, "masterdns-server"), 0o755)
    os.chmod(os.path.join(client_dir, "masterdns-client"), 0o755)

    with open(os.path.join(target_dir, "hello.txt"), "w") as fh:
        fh.write(MARKER)

    procs = []
    logs = {}
    try:
        for name, cmd, cwd in [
            ("target", [sys.executable, "-m", "http.server", str(TARGET_PORT)], target_dir),
            ("server", ["./masterdns-server"], server_dir),
            ("client", ["./masterdns-client"], client_dir),
        ]:
            logs[name] = open(os.path.join(tmp, f"{name}.log"), "wb")
            procs.append(subprocess.Popen(cmd, cwd=cwd, stdout=logs[name],
                                          stderr=subprocess.STDOUT))
        # curl must not bypass the proxy for localhost: strip no_proxy.
        clean_env = {k: v for k, v in os.environ.items()
                     if k.lower() not in ("no_proxy", "http_proxy", "https_proxy")}
        deadline = time.time() + 90
        body = ""
        while time.time() < deadline:
            proc = subprocess.run(
                ["curl", "-s", "--max-time", "10", "--socks5-hostname",
                 f"127.0.0.1:{SOCKS_PORT}", f"http://127.0.0.1:{TARGET_PORT}/hello.txt"],
                capture_output=True, text=True, env=clean_env)
            body = proc.stdout.strip()
            if body == MARKER:
                break
            time.sleep(3)
        assert body == MARKER, f"tunnel did not carry traffic; last body={body!r}"
        print("E2E TEST: real MasterDnsVPN server + client carried traffic "
              "using panel-generated configs only")
    finally:
        for p in procs:
            p.terminate()
        for p in procs:
            try:
                p.wait(timeout=5)
            except subprocess.TimeoutExpired:
                p.kill()
        for name, fh in logs.items():
            fh.close()
            tail = open(os.path.join(tmp, f"{name}.log"), errors="replace").read()[-1500:]
            print(f"--- {name} log tail ---\n{tail}")


if __name__ == "__main__":
    main()
